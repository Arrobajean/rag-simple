-- 0018 · Registro de accesos: quién entra, con qué rol, por qué método y desde qué dispositivo

create table if not exists accesos (
  id bigint generated by default as identity primary key,
  email text,                                        -- null en el acceso por contraseña (no hay identidad que registrar)
  rol text not null check (rol in ('admin', 'gestor', 'visitante')),
  metodo text not null check (metodo in ('linkedin', 'contrasena')),
  user_agent text,
  created_at timestamptz not null default now()
);
create index if not exists accesos_created_idx on accesos(created_at desc);
create index if not exists accesos_email_idx on accesos(lower(email));
alter table accesos enable row level security;
