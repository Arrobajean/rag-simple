-- 0019 · Soporte y feedback: mensajes que dejan los usuarios desde el sidebar

create table if not exists soporte (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('soporte', 'feedback')),
  email text,                                        -- null si el mensaje llega sin sesión de LinkedIn y sin email indicado
  nombre text,
  rol text check (rol in ('admin', 'gestor', 'visitante')),
  mensaje text not null,
  estado text not null default 'nuevo' check (estado in ('nuevo', 'revisado')),
  user_agent text,
  created_at timestamptz not null default now()
);
create index if not exists soporte_created_idx on soporte(created_at desc);
create index if not exists soporte_tipo_idx on soporte(tipo);
alter table soporte enable row level security;
